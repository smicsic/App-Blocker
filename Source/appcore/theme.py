"""Цветовая палитра, шрифты и константы оформления интерфейса.

Оформление в духе Epic Games Store: почти чёрный нейтральный фон с лёгким
синим подтоном, плоские поверхности без цветных подсветок, малые радиусы
скругления и один акцентный синий, которым выделены только действия. Серый —
для структуры, синий — для того, что нажимают.

Модуль не зависит от библиотеки интерфейса: здесь только строки цветов и числа,
которые Flet принимает напрямую (``bgcolor="#17171C"``, ``border_radius=8``).
"""

# ---------- Поверхности ----------
# Разница между уровнями намеренно небольшая: «дорогой» тёмный интерфейс строится
# на еле заметных перепадах яркости, а не на контрастных плашках.
APP_BG = "#0B0B0F"            # фон окна (и низ подложки)
BACKDROP_TOP = "#131319"      # верх подложки: еле заметный перепад для глубины
SIDEBAR_BG = "#101014"        # боковая навигация
TOPBAR_BG = "#101014"
PANEL_BG = "#131318"          # панель логов
CARD_BG = "#17171C"           # карточки
CARD_HOVER = "#22222A"
ROW_BG = "#15151A"            # строки списков
ROW_HOVER = "#1F1F26"
INPUT_BG = "#0E0E12"          # поля ввода — темнее карточки, «вдавленные»
DISABLED_BG = "#16161B"

# ---------- Границы ----------
BORDER_COLOR = "#2A2A32"
BORDER_SUBTLE = "#1E1E25"

# ---------- Акцент ----------
# Синий EGS. Держим его только на кнопках и активных значениях, иначе
# интерфейс перестаёт читаться как дорогой.
PRIMARY = "#0078F2"
PRIMARY_HOVER = "#2A90FF"
SECONDARY = "#26BBFF"
# Используется как hover для основных кнопок в существующих вкладках.
SECONDARY_HOVER = "#2A90FF"
ACCENT = "#3FA0FF"

# ---------- Нейтральные кнопки ----------
SECONDARY_BG = "#26262E"
SECONDARY_BG_HOVER = "#33333D"

# ---------- Статусы ----------
SUCCESS = "#37C267"
WARNING = "#F5A623"
ERROR = "#E5484D"
ERROR_HOVER = "#F0666A"

# ---------- Текст ----------
TEXT_MAIN = "#FFFFFF"
TEXT_MUTED = "#8E8E9A"

# ---------- Геометрия ----------
# EGS избегает «таблеток»: у карточек мягкое, но небольшое скругление,
# у кнопок — почти прямые углы.
CARD_RADIUS = 8
BUTTON_RADIUS = 4
BORDER_WIDTH = 1

# ---------- Шрифты ----------
APP_FONT_FILE = "Huninn-Regular.ttf"
APP_FONT_FAMILY = "Huninn"
# Segoe UI — системный шрифт Windows: нейтральный и строгий. Фирменный Huninn
# скруглённый и дружелюбный, он спорит с типографикой EGS. Чтобы вернуть его,
# достаточно написать FONT_FAMILY = APP_FONT_FAMILY: файл шрифта регистрируется
# в page.fonts при старте окна (см. gui/shell.py).
FONT_FAMILY = "Segoe UI"
# Consolas есть в любой Windows, в отличие от JetBrains Mono: если моношрифт не
# установлен, подставится системный, и панель логов будет выглядеть случайной.
MONO_FONT_FAMILY = "Consolas"

ANTIVIRUS_GUIDE_URL = "https://www.youtube.com/watch?v=pG03P8DdJzg"
DEFENDER_EXCLUSIONS_URI = "windowsdefender://exclusions"
